-- Run this once in the Supabase SQL Editor for the project used by this app.
-- Keep the service role key in Vercel server-side environment variables only.

create table if not exists public.scan_history (
    id bigint generated by default as identity primary key,
    user_id uuid not null,
    entry jsonb not null,
    created_at timestamptz not null default now()
);

create index if not exists scan_history_user_created_at_idx
    on public.scan_history (user_id, created_at desc);

alter table public.scan_history enable row level security;

revoke all on table public.scan_history from public, anon, authenticated;
grant all on table public.scan_history to service_role;

create table if not exists public.feedback (
    id bigint generated by default as identity primary key,
    username text not null default 'Anonymous' check (char_length(username) between 1 and 24),
    rating smallint not null check (rating between 1 and 5),
    comment text not null default '' check (char_length(comment) <= 500),
    created_at timestamptz not null default now()
);

-- Add the display name column to feedback tables created before usernames were supported.
alter table public.feedback
    add column if not exists username text not null default 'Anonymous'
    check (char_length(username) between 1 and 24);

create index if not exists feedback_created_at_idx
    on public.feedback (created_at desc);

alter table public.feedback enable row level security;

revoke all on table public.feedback from public, anon, authenticated;
grant select, insert on table public.feedback to service_role;

notify pgrst, 'reload schema';
